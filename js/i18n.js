let lang = 'en';

function applyLanguage(nextLang) {
    lang = nextLang;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const value = strings[lang]?.[el.dataset.i18n];
        if (value) el.innerHTML = value;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        if (key === 'search.placeholder') el.placeholder = lang === 'en' ? 'Search for an opportunity, cause or organization...' : 'Busca una oportunidad, causa u organización...';
    });
    document.querySelectorAll('.lang-option').forEach(btn => {
        const active = btn.dataset.lang === lang;
        btn.classList.toggle('active', active);
        btn.setAttribute('aria-pressed', String(active));
    });
    localStorage.setItem('bv-lang', lang);
}

document.querySelectorAll('.lang-option').forEach(btn => {
    btn.addEventListener('click', () => applyLanguage(btn.dataset.lang));
});

// English is the default. We only restore Spanish if the visitor explicitly chose it before.
const savedLang = localStorage.getItem('bv-lang');
applyLanguage(savedLang === 'es' ? 'es' : 'en');
